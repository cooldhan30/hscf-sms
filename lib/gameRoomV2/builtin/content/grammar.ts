function classify(question: string, options: string[], items: [string, string][]): BuiltinQuestion[] {
  return items.map(([word, answer]) =>
    mc(
      `"${word}" -- ${question}`,
      answer,
      options.filter((o) => o !== answer),
      NOTES[answer]
    )
  )
}

